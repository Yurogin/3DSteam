const DICTS = { fr, en };
export type Lang = keyof typeof DICTS;

export const LANGS: { id: Lang; label: string; locale: string }[] = [
  { id: "fr", label: "Français", locale: "fr-FR" },
  { id: "en", label: "English", locale: "en-US" },
];

export const defaultLang = (): Lang => (navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en");

type Vars = Record<string, string | number>;

interface I18n {
  lang: Lang;
  /** Locale pour les dates et nombres (`fr-FR`, `en-US`). */
  locale: string;
  setLang: (lang: Lang) => void;
  t: (key: Key, vars?: Vars) => string;
  /** Pluriel : `tn("games", 3)` → clé `games_other` avec `{n}` = 3. */
  tn: (base: "games" | "folders" | "albums" | "tracks", n: number) => string;
}

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const stored = load<string>("lang", "");
    return stored in DICTS ? (stored as Lang) : defaultLang();
  });

  useEffect(() => {
    save("lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback(
    (key: Key, vars?: Vars) => {
      const text = DICTS[lang][key] ?? fr[key];
      return vars ? text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : text;
    },
    [lang],
  );

  const value = useMemo<I18n>(
    () => ({
      lang,
      locale: LANGS.find((l) => l.id === lang)?.locale ?? "fr-FR",
      setLang,
      t,
      // Français : 0 et 1 au singulier ; anglais : seul 1 est au singulier.
      tn: (base, n) => t(`${base}_${(lang === "fr" ? n > 1 : n !== 1) ? "other" : "one"}` as Key, { n }),
    }),
    [lang, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n doit être utilisé sous <I18nProvider>");
  return ctx;
}

export type TFunction = I18n["t"];
